/// Turns the bank rows for [topicId] into quiz questions.
List<GrammarQuizQuestion> c2BankQuestions(String topicId) {
  final rows = c2QuizBank[topicId];
  if (rows == null) return const [];
  return List<GrammarQuizQuestion>.generate(rows.length, (index) {
    final row = rows[index];
    return GrammarQuizQuestion(
      id: '${topicId}_bank_${index + 1}',
      type: GrammarQuizType.fillBlank,
      prompt: 'Complete the sentence.',
      sentence: row[0] as String,
      options: (row[1] as List).cast<String>(),
      answer: row[2] as String,
      explanation: row[3] as String,
    );
  });
}
